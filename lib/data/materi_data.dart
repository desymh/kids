  static List<Map<String, dynamic>> getPoinPenjelasan(
    Map<String, dynamic> item,
  ) {
    final rawPoints = item['poinPenjelasan'];
    final points = <Map<String, dynamic>>[];

    if (rawPoints is List) {
      for (final rawPoint in rawPoints) {
        if (rawPoint is! Map) continue;

        final judul = rawPoint['judulPoin']?.toString().trim() ?? '';
        final isi = rawPoint['isiPenjelasan']?.toString().trim() ?? '';
        if (judul.isEmpty || isi.isEmpty) continue;

        points.add({'judulPoin': judul, 'isiPenjelasan': isi});
      }
    }

    if (points.isNotEmpty) return points;

    final explanation = item['penjelasanAnak']?.toString().trim() ?? '';
    if (explanation.isEmpty) return points;

    final sentences = explanation
        .split(RegExp(r'(?<=[.!?])\s+'))
        .map((sentence) => sentence.trim())
        .where((sentence) => sentence.isNotEmpty)
        .toList();
    final title = item['judulKartu']?.toString().trim() ?? 'Penjelasan';

    return [
      for (var i = 0; i < sentences.length; i++)
        {
          'judulPoin': sentences.length == 1 ? title : '$title ${i + 1}',
          'isiPenjelasan': sentences[i],
        },
    ];
  }
